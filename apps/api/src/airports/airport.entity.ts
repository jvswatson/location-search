import { Column, Entity, PrimaryGeneratedColumn } from 'typeorm';
import type { Point } from 'geojson';

@Entity({ name: 'airports' })
export class Airport {
  @PrimaryGeneratedColumn()
  id: number;

  @Column({ name: 'icao_code', type: 'char', length: 4, unique: true })
  icaoCode: string;

  @Column({ name: 'iata_code', type: 'char', length: 3, nullable: true })
  iataCode: string | null;

  @Column({ type: 'text' })
  name: string;

  @Column({ type: 'text' })
  city: string;

  @Column({ type: 'text' })
  country: string;

  @Column({ name: 'altitude_ft', type: 'integer' })
  altitudeFt: number;

  @Column({ type: 'geography', spatialFeatureType: 'Point', srid: 4326 })
  geog: Point;

  // Generated by Postgres (see migration); never written by the app.
  @Column({ name: 'search_vector', type: 'tsvector', select: false, insert: false, update: false })
  searchVector?: string;
}
